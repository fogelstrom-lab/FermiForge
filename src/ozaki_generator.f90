  subroutine ozaki_poles(M,zp,Rp)
!  subroutine ozaki_poles(M)
!-----------------------------------------------------------------------------!
    integer, intent(in) :: M ! cutoff (number of poles we will get)
    real(rk), dimension(1:M), intent(out) :: zp,Rp ! poles (positive) and residues

    integer :: N,i,itype,lda,ldb,lwork,info
    character(len=1) :: jobz,uplo
    real(rk), dimension(:), allocatable :: W,work
    real(rk), dimension(:,:), allocatable :: A,B

    if (M < 1 .or. M > 200) error stop "Ozaki pole count out of range"

    N = 2*M ! matrix must have N even
    lda = N
    ldb = N
    lwork = 3*N
    itype = 1  ! generalized eigenvalue problem of type A*x = (lambda)*B*x
    jobz = 'V' ! Compute eigenvalues and eigenvectors
    uplo = 'U' ! Upper triangles of A and B are stored

    allocate( A(N,N) )
    allocate( B(N,N) )
    allocate( W(N) )
    allocate( work(lwork) )

    ! trick to get eigenvalues: divide down (lambda), i.e. exchange A and B from the Ozaki paper

    B = 0.0_rk
    do i = 1, N
       B(i,i) = i*2.0_rk-1.0_rk
    end do

    A = 0.0_rk
    do i = 1, N-1
       A(i,i+1) = -0.5_rk
       A(i+1,i) = -0.5_rk
    end do

    call dsygv( itype, jobz, uplo, N, A, lda, B, ldb, W, work, lwork, info )

    if( info.ne.0 )then
       write(*,*) 'Ozaki_poles dsygv returned info = ', info
       error stop "Ozaki eigensolver failed"
    end if

    ! poles
    do i = 1, M
       zp(i) = -1.0_rk/W(i)
    end do

    ! residues
    do i = 1, M
       Rp(i) = 0.25_rk*A(1,i)*A(1,i)*zp(i)*zp(i)
    end do
    ! print zp and Rp

    deallocate( A )
    deallocate( B )
    deallocate( W )
    deallocate( work )
!-----------------------------------------------------------------------------!
  end subroutine ozaki_poles
